export const TEXTS = { en, ru } as const;
export type Language = keyof typeof TEXTS;

/** The first browser language we have, Russian or English; English when none of them fits. */
export function pickLanguage(preferred: readonly string[]): Language {
  for (const tag of preferred) {
    const base = tag.toLowerCase().split('-')[0];
    if (base === 'ru' || base === 'en') return base;
  }
  return 'en';
}

/** Puts values into {name} places of a text. */
export const fill = (text: string, values: Record<string, string | number>) =>
  text.replace(/\{(\w+)\}/g, (all, key: string) => (key in values ? String(values[key]) : all));

/** Whole numbers with an unbreakable space between thousands, the same in every language: 11 000, 1 250 000. */
export const formatScore = (n: number) => String(Math.round(n)).replace(/\B(?=(\d{3})+(?!\d))/g, '\u00a0');
